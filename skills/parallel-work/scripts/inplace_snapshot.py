"""Snapshot a folder before in-place parallel work, then list what changed. Works the same on macOS, Linux and Windows.

Usage:
  python3 -I inplace_snapshot.py snapshot <folder> <state dir> [--backup] [--exclude NAME ...]
  python3 -I inplace_snapshot.py changed  <folder> <state dir> [--exclude NAME ...]

snapshot records every file's size and modification time in <state dir>/manifest.json,
and with --backup also copies the files to <state dir>/backup/.
changed compares the folder with that manifest and prints added, modified and deleted files.
"""
import argparse
import json
import os
import shutil
import sys

# Folder names skipped anywhere in the tree: VCS data, dependencies and tool caches. They are large,
# regenerated by tools, and not what workers edit. Build output names (build, dist, target) are left in:
# in a plain folder they may hold sources, so the caller opts in with --exclude.
DEFAULT_EXCLUDES = {'.git', '.hg', '.svn', 'node_modules', '.venv', 'venv', '__pycache__',
                    '.gradle', '.next', '.nuxt', '.idea', '.worktrees'}
MANIFEST = 'manifest.json'


def walk(folder, excludes):
    result = {}
    for cur, dirs, files in os.walk(folder):
        dirs[:] = [d for d in dirs if d not in excludes]
        for name in files:
            path = os.path.join(cur, name)
            try:
                st = os.lstat(path)
            except OSError:
                continue
            rel = os.path.relpath(path, folder).replace(os.sep, '/')
            result[rel] = [st.st_size, st.st_mtime_ns]
    return result


def snapshot(folder, state, excludes, backup):
    state_real = os.path.realpath(state)
    if state_real == folder or state_real.startswith(folder + os.sep):
        sys.exit('ERROR: the state dir must be outside the folder (use the scratchpad): ' + state)
    dest = os.path.join(state, 'backup')
    if backup and os.path.exists(dest):
        sys.exit('ERROR: %s already exists. Ask the user before replacing an earlier backup' % dest)
    files = walk(folder, excludes)
    os.makedirs(state, exist_ok=True)
    with open(os.path.join(state, MANIFEST), 'w', encoding='utf-8') as f:
        json.dump({'folder': folder, 'excludes': sorted(excludes), 'files': files}, f)
    if backup:
        for rel in files:
            src, dst = os.path.join(folder, *rel.split('/')), os.path.join(dest, *rel.split('/'))
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(src, dst, follow_symlinks=False)
        print('backup:   %s (%d files)' % (dest, len(files)))
    print('snapshot: %d files recorded in %s' % (len(files), os.path.join(state, MANIFEST)))
    print('skipped folders: ' + ' '.join(sorted(excludes)))


def changed(folder, state, excludes):
    path = os.path.join(state, MANIFEST)
    if not os.path.exists(path):
        sys.exit('ERROR: no snapshot at %s. Run `snapshot` before launching workers' % path)
    with open(path, encoding='utf-8') as f:
        before = json.load(f)
    if os.path.normcase(before['folder']) != os.path.normcase(folder):
        sys.exit('ERROR: the snapshot was taken of %s, not %s' % (before['folder'], folder))
    excludes |= set(before['excludes'])
    # Folders excluded only now were not walked, so drop their old entries rather than report them deleted.
    old = {k: v for k, v in before['files'].items() if not set(k.split('/')[:-1]) & excludes}
    new = walk(folder, excludes)
    added = sorted(set(new) - set(old))
    deleted = sorted(set(old) - set(new))
    modified = sorted(k for k in set(new) & set(old) if new[k] != old[k])
    for label, items in (('added', added), ('modified', modified), ('deleted', deleted)):
        print('%s (%d)' % (label, len(items)))
        for item in items:
            print('  ' + item)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('command', choices=('snapshot', 'changed'))
    p.add_argument('folder')
    p.add_argument('state')
    p.add_argument('--backup', action='store_true')
    p.add_argument('--exclude', action='append', default=[], metavar='NAME')
    a = p.parse_args()
    folder = os.path.realpath(a.folder)
    if not os.path.isdir(folder):
        sys.exit('ERROR: not a folder: ' + a.folder)
    excludes = DEFAULT_EXCLUDES | set(a.exclude)
    if a.command == 'snapshot':
        snapshot(folder, a.state, excludes, a.backup)
    else:
        changed(folder, a.state, excludes)


if __name__ == '__main__':
    main()
